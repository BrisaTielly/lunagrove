const DIGIT_GAP = 2;
const COLON_GAP = 3;

function glyphRects(glyph: string[], offsetX: number): string {
  let path = "";
  glyph.forEach((row, y) => {
    for (const match of row.matchAll(/#+/g)) {
      const left = offsetX + match.index;
      path += `M${left} ${y}h${match[0].length}v1H${left}z`;
    }
  });
  return path;
}

export function PixelDigits({ text, unit }: { text: string; unit: number }) {
  let x = 0;
  let path = "";
  [...text].forEach((char, index) => {
    const glyph = GLYPHS[char];
    if (!glyph) return;
    const colonNearby = char === ":" || text[index - 1] === ":";
    if (index > 0) x += colonNearby ? COLON_GAP : DIGIT_GAP;
    path += glyphRects(glyph, x);
    x += glyph[0].length;
  });

  return (
    <svg
      className="pixel-digits-art"
      aria-hidden="true"
      viewBox={`0 0 ${x} 16`}
      width={x * unit}
      height={16 * unit}
      shapeRendering="crispEdges"
    >
      <path d={path} fill="currentColor" />
    </svg>
  );
}
